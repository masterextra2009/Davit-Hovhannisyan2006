-- Согласие на рекламные уведомления (38-ФЗ, ст. 18).
--
-- Новости и акции — это реклама, и слать её можно только тем, кто сам
-- согласился; по умолчанию согласия нет. Уведомления о своём заказе и ответы
-- в чате рекламой не являются и приходят всегда, независимо от этого поля.
--
-- Сам факт согласия и его отзыв пишутся в таблицу consents (kind='marketing',
-- granted 1/0) — там история с датой, версией документа и источником. Здесь
-- же хранится только текущее состояние, чтобы рассылка могла отобрать
-- получателей одним запросом.

ALTER TABLE users
  ADD COLUMN marketing_consent TINYINT(1) NOT NULL DEFAULT 0 AFTER expo_push_token;
