-- Код из письма для смены пароля: докладка к schema-007-password-reset.sql.
--
-- Зачем. В письме до сих пор была только ссылка, и она вела на sever-18.ru.
-- В браузере это правильно, а вот в приложении — нет: телефон открывает
-- ссылку в браузере и уводит клиента на сайт, где он оказывается на странице,
-- больше похожей на обычный вход. Давид 22.09.2026: «не надо, чтобы отправлял
-- на сайт, пусть там же в приложении».
--
-- Поэтому рядом со ссылкой в письме теперь шесть цифр. Их вводят прямо в
-- приложении, никуда не уходя. Ссылка остаётся — ею пользуется сайт.
--
-- Храним не сам код, а его отпечаток, и солим номером клиента: одинаковые
-- шесть цифр у разных людей должны давать разные отпечатки.
--
-- tries — счётчик неверных попыток на конкретный код. Перебор и так закрыт
-- общим ограничителем (10 обращений за 5 минут на все действия входа), но
-- пусть у самого кода будет свой предел: шесть цифр — это немного.

SET NAMES utf8mb4;

ALTER TABLE password_resets
  ADD COLUMN code_hash CHAR(64) NULL AFTER token_hash,
  ADD COLUMN tries TINYINT UNSIGNED NOT NULL DEFAULT 0;
