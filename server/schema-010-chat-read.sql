-- Когда сообщение отметили прочитанным: докладка к schema-004-chat.sql.
--
-- Зачем. Чат опрашивает сервер вопросом «что нового с такого-то времени», и
-- сервер отдавал только сообщения, СОЗДАННЫЕ после этого времени. Отметка
-- «прочитано» ставится на уже старое сообщение — поэтому до собеседника она
-- не доходила, пока чат не открыть заново. Давид 24.09.2026: «когда я в
-- админке увидел сообщение, на телефоне не стало две галочки».
--
-- Теперь mark_read ставит read_changed_at, и опрос отдаёт сообщение ещё раз,
-- если его прочитали после прошлого опроса.

SET NAMES utf8mb4;

ALTER TABLE chat_messages
  ADD COLUMN read_changed_at DATETIME(3) NULL AFTER read_by_client,
  ADD KEY ix_chat_read_changed (read_changed_at);
