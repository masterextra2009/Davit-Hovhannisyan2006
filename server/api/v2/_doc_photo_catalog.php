/** Сколько штук за 250 ₽ — правило Давида 03.10.2026: 3,5×4,5 — 4, 3×4 — 6, 4×6 — 4, 9×12 — 1, прочие — 4. */
function doc_photo_copies(array $doc): int
{
    if (!empty($doc['copies'])) {
        return (int) $doc['copies'];
    }
    $size = $doc['w'] . 'x' . $doc['h'];
    return ['35x45' => 4, '30x40' => 6, '40x60' => 4, '90x120' => 1][$size] ?? 4;
}

